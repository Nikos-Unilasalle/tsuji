"""Writes public/demos/demo_music_pocket_star.tsuji — "Pocket Star", a soft, melodic chiptune in C major on Game Boy
channels (100 BPM, 48 bars, about two minutes).

The two tunes are written (Pattern nodes, an A theme and a B theme); everything around them is generated by the
music nodes:

- one Progression for the whole form, voice-led, played as broken chords in eighths on the wave channel's sine, its
  roots as a round bass in quarters;
- the second time round, a second-species Counterpoint under each theme and a soft Chip Echo on another pulse;
- the bridge: a Markov chain that learned both themes improvises a new tune;
- a gentle DMG kit on Euclidean rhythms; Sections for the form; a Music Viewer in the Chip palette.

Sounds stay soft and in the middle of the range: the lead a 50 % pulse with a late vibrato, nothing above F5. The
counterpoint and Markov seeds were picked by search, scoring how their notes sit on the chords.

Run: python3 tools/gen_music_demo.py
"""
from pathlib import Path
import json
BARS = 48
def mask(*ranges):
    on = [False]*BARS
    for a, b in ranges:            # 1-based, inclusive
        for i in range(a-1, b): on[i] = True
    out, i = [], 0
    while i < BARS:
        j = i
        while j < BARS and on[j] == on[i]: j += 1
        out.append(('x' if on[i] else '.') + (f'*{j-i}' if j-i > 1 else ''))
        i = j
    return ' '.join(out)

# Seeds chosen by search (see the docstring): the counter-melodies and the bridge tune that sit best on the chords.
CP_A_SEED, CP_B_SEED = 22, 327
MK_ORDER, MK_NOVELTY, MK_SEED = 2, 0.15, 312

nodes, conns, tracks = [], [], []
def node(id, ntype, x, y, **params):
    nodes.append({"id": id, "type": ntype, "position": {"x": x, "y": y}, "params": params}); return id
def wire(a, b, fs="sequence", ts="sequence"):
    conns.append({"id": f"c{len(conns)}", "fromNode": a, "fromSocket": fs, "toNode": b, "toSocket": ts})
def sec(id, src, x, y, name, ranges, restart=True, fs="sequence"):
    when = ", ".join(f"{a}–{b}" for a, b in ranges)
    node(id, "music/sections", x, y, name=f"{name} · bars {when}", bars=mask(*ranges), barLength=16, restart=restart)
    wire(src, id, fs); return id
def gb(id, x, y, src, name, preset, level, pan=0, fs="sequence", **extra):
    node(id, "music/gameboy", x, y, name=name, preset=preset, level=level, pan=pan, **extra)
    wire(src, id, fs); tracks.append(id); return id

X = [0, 260, 520, 780, 1040, 1300]
node("clock", "music/clock", -320, 700, bpm=100, swing=0, stepsPerBeat="4")

def bars(*bs):
    """One string per bar, padded to 16 steps."""
    words = []
    for b in bs:
        w = b.split()
        assert len(w) <= 16, b
        words += w + ["."] * (16 - len(w))
    return " ".join(words)

# ── Harmony: one progression for the whole song, in C major ─────────────────
A_CHORDS = "I vi IV V I vi ii:0.5 V:0.5 I"
B_CHORDS = "IV V iii vi IV V I I"
FORM = [("Intro", 1, 4, "I vi IV V"),
        ("A", 5, 12, A_CHORDS),
        ("B", 13, 20, B_CHORDS),
        ("Bridge", 21, 28, "vi IV I V vi IV ii:0.5 V:0.5 V"),
        ("A", 29, 36, A_CHORDS),
        ("B", 37, 44, B_CHORDS),
        ("Outro", 45, 48, "IV V I:2")]
A1, B1, BR, A2, B2 = [(5, 12)], [(13, 20)], [(21, 28)], [(29, 36)], [(37, 44)]
y = 0
node("prog", "music/progression", X[0], y, root="C", mode="major", source="written", numerals=" ".join(f[3] for f in FORM),
     count=8, sevenths=False, tension=0.3, cadence=True, seed=0, chordLength=16, center=60, velocity=0.6)
wire("clock", "prog", "clock", "clock")
node("vl", "music/voice-leading", X[1], y, voices=3, low=55, high=67); wire("prog", "vl", "chords")
# soft broken chords in eighths, on the wave channel's sine
node("arp", "music/arp", X[2], y, on=True, mode="updown", rate="1/8", triplet=False, octaves=1, gate=0.8, sync="grid"); wire("vl", "arp")
sec("sec_arp", "arp", X[3], y, "broken chords", [(1, 48)], restart=False)
gb("arp_v", X[4], y, "sec_arp", "Broken chords", "Wave · Sine", 0.3, -0.25)
# the bass: the roots in quarters, an octave up from where they are voiced (G2–F3: round on the wave channel)
node("bounce", "music/arp", X[2], y+160, on=True, mode="up", rate="1/4", triplet=False, octaves=1, gate=0.85, sync="grid"); wire("vl", "bounce", "bass")
sec("sec_bass", "bounce", X[3], y+160, "bass", [(3, 46)], restart=False)
gb("bass_v", X[4], y+160, "sec_bass", "Bass", "Wave · Bass", 0.45, transpose=12)

# ── The tunes, written: an A theme and a B theme ─────────────────────────────
y = 420
THEME_A = bars(
    "E4 . . . G4 . C5 . B4 . . . G4 . . .",
    "A4 . . . . . C5 . E5 . . . D5 . C5 .",
    "C5 . . . A4 . . . F4 . G4 . A4 . . .",
    "G4 . . . . . . . D4 . E4 . F4 . G4 .",
    "E4 . . . G4 . C5 . E5 . . . D5 . C5 .",
    "C5 . . . B4 . A4 . E4 . . . A4 . . .",
    "F4 . . . A4 . D5 . B4 . . . D5 . . .",
    "C5 . . . . . . . . . . . off")
THEME_B = bars(
    "A4 . . . C5 . . . F5 . . . E5 . D5 .",
    "D5 . . . . . B4 . G4 . . . . . . .",
    "G4 . . . B4 . . . E5 . . . D5 . B4 .",
    "C5 . . . . . . . A4 . . . . . . .",
    "A4 . . . C5 . F5 . E5 . . . D5 . C5 .",
    "D5 . . . . . E5 . D5 . . . B4 . G4 .",
    "C5 . . . . . . . E4 . . . G4 . . .",
    "C5 . . . . . . . . . . . off")
node("theme_a", "music/pattern", X[0], y, name="Theme A (written)", steps=THEME_A, length="128"); wire("clock", "theme_a", "clock", "clock")
node("theme_b", "music/pattern", X[0], y+200, name="Theme B (written)", steps=THEME_B, length="128"); wire("clock", "theme_b", "clock", "clock")
sec("sec_a", "theme_a", X[3], y, "theme A", A1 + A2)
sec("sec_b", "theme_b", X[3], y+200, "theme B", B1 + B2)
gb("lead_a", X[4], y, "sec_a", "Lead · A", "Macro · Vibrato Lead", 0.38, 0.05)
gb("lead_b", X[4], y+200, "sec_b", "Lead · B", "Macro · Vibrato Lead", 0.38, 0.05)
# the second time round, a soft echo on another pulse
node("echo_a", "music/chip-echo", X[4], y+80, delay=3, level=0.35, transpose=0, detune=4); wire("sec_a", "echo_a")
node("echo_b", "music/chip-echo", X[4], y+280, delay=3, level=0.35, transpose=0, detune=4); wire("sec_b", "echo_b")
sec("sec_echo_a", "echo_a", X[5], y+80, "echo A", A2, restart=False, fs="echo")
sec("sec_echo_b", "echo_b", X[5], y+280, "echo B", B2, restart=False, fs="echo")
gb("echo_a_v", X[5]+260, y+80, "sec_echo_a", "Echo · A", "Pulse 50 · Lead", 0.22, 0.45)
gb("echo_b_v", X[5]+260, y+280, "sec_echo_b", "Echo · B", "Pulse 50 · Lead", 0.22, 0.45)

# ── Generated around them: a counter-melody under each theme, the second time ──
y = 900
node("cp_a", "music/counterpoint", X[1], y, species="2", position="below", scale="major", root="C", low=50, high=62, velocity=0.6, seed=CP_A_SEED); wire("theme_a", "cp_a")
node("cp_b", "music/counterpoint", X[1], y+160, species="2", position="below", scale="major", root="C", low=50, high=62, velocity=0.6, seed=CP_B_SEED); wire("theme_b", "cp_b")
sec("sec_cp_a", "cp_a", X[3], y, "counter-melody A", A2)
sec("sec_cp_b", "cp_b", X[3], y+160, "counter-melody B", B2)
gb("cp_a_v", X[4], y, "sec_cp_a", "Counter · A", "Pulse 50 · Lead", 0.18, -0.4)
gb("cp_b_v", X[4], y+160, "sec_cp_b", "Counter · B", "Pulse 50 · Lead", 0.18, -0.4)

# ── Bridge: a Markov chain that learned both themes improvises a new tune ────
y = 1260
node("markov", "music/markov", X[1], y, order=MK_ORDER, length=128, learn="both", novelty=MK_NOVELTY, seed=MK_SEED)
wire("theme_a", "markov", "sequence", "source"); wire("theme_b", "markov", "sequence", "source2")
node("scale_m", "music/scale", X[2], y, root="C", scale="major", snap="nearest", outside="snap", chords="keep"); wire("markov", "scale_m")
sec("sec_mk", "scale_m", X[3], y, "bridge tune", BR)
gb("markov_v", X[4], y, "sec_mk", "Bridge · Markov", "Macro · Vibrato Lead", 0.34, -0.05)

# ── Drums: a gentle DMG kit on Euclidean rhythms ─────────────────────────────
y = 1500
for i, (id, notes, p, s, rot, vel, ranges, name, level) in enumerate([
    ("kick", "kick", 2, 16, 0, 0.8, [(5, 44)], "Kick", 0.36),
    ("snare", "snare", 2, 16, 4, 0.55, [(13, 20), (29, 44)], "Snare", 0.3),
    ("hats", "hat", 4, 16, 2, 0.35, [(13, 20), (37, 44)], "Hats", 0.3)]):
    yy = y + i*160
    node(f"eu_{id}", "music/euclid", X[0], yy, pulses=p, steps=s, rotation=rot, notes=notes, gate=0, velocity=vel, accent=0)
    wire("clock", f"eu_{id}", "clock", "input")
    sec(f"sec_{id}", f"eu_{id}", X[3], yy, id, ranges)
    gb(f"kit_{id}", X[4], yy, f"sec_{id}", name, "Kit · DMG Drums", level)

# ── Out, the viewer, the render ─────────────────────────────────────────────
node("out", "music/out", 1900, 1100, master=0.8, startFrame=0)
for i, t in enumerate(tracks): wire(t, "out", "track", f"track{i}")
node("viewer", "music/viewer", 1900, 800, title="Pocket Star", show=True, style="galaxy", palette="chip", intensity=0.9, ahead=5, legend=True)
seconds = BARS * 16 / 4 / 100 * 60
node("env", "lighting/environment", 1900, 1400, color=0x0b1a10, intensity=1, background=1, ambientIntensity=0.6, sunIntensity=1.2)
node("render", "render", 1900, 1600, frameCount=int(round(seconds * 30)), fps=30, motionBlur=0, resolutionPreset="16:9 (1920x1080)", width=1920, height=1080, holdout=False)
# a sphere breathing with the kick (seen when the viewer is hidden)
node("probe", "music/note-probe", 2200, 1100, decay=0.3); wire("sec_kick", "probe", "sequence", "music")
node("pulse", "math/expression", 2440, 1100, formula="0.7 + 0.5 * x"); wire("probe", "pulse", "envelope", "x")
node("to_vec", "converter/value-to-vector", 2680, 1100); wire("pulse", "to_vec", "value", "value")
node("xform", "transform/matrix-transform", 2920, 1100); wire("to_vec", "xform", "vector", "scale")
node("sphere", "object/sphere", 3160, 1100, color=0x9bbc0f, emissive=0x1e3a0f, emissiveIntensity=1.0); wire("xform", "sphere", "matrix", "matrix")
doc = {"canvases": [{"nodes": nodes, "connections": conns, "keyframes": {}, "markers": [], "exposedParams": []}], "activeCanvas": 0}
OUT = Path(__file__).resolve().parent.parent / "public" / "demos" / "demo_music_pocket_star.tsuji"
OUT.write_text(json.dumps(doc, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
print(len(nodes), "nodes", len(tracks), "tracks", round(seconds, 1), "s")
