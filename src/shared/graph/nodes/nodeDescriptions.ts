/** Fills a node's description from the table above when the node file doesn't set one (in place, as addPoseSockets does). */
export function withDescription(def: NodeDefinition): NodeDefinition {
  if (!def.description && NODE_DESCRIPTIONS[def.type]) def.description = NODE_DESCRIPTIONS[def.type];
  return def;
}
